# 3. Product of Beta distributions
# ============================================================================

class BetaProduct(Problem):
    """Product of Beta distributions as likelihood, flat cube prior.

    logL(x) = sum_i log Beta-pdf(x_i; a_i, b_i)

    The posterior is the product of the betas itself, so lnZ = 0 and H is
    the sum of the negative differential entropies of the betas.

    By default the shape parameters are drawn as 10^Uniform(0, 1), i.e.
    a_i, b_i in [1, 10], so the log-density is concave and vanishes at the
    cube faces; the constrained region is convex and well-behaved.

    Shape parameters below one (alphamin < 0) make the density diverge at
    the faces. The constrained region then has extremely anisotropic spike
    geometry whose anisotropy varies by orders of magnitude across the
    region; the MH-corrected direction scaling used here can then freeze at
    extreme thresholds, so such settings are not recommended as validation
    problems.

    The chord endpoints along a hit-and-run line are found exactly: for
    a_i, b_i > 1 the log-likelihood is concave along the line (single
    interval, bisection). Otherwise the critical points of the
    log-likelihood along the line (roots of a polynomial of degree
    <= 2*ndim - 1) split the chord into monotone pieces, each resolved by
    bisection, and the position is drawn from the union of allowed
    intervals.
    """

    def __init__(self, ndim, alphamin=0, alphamax=1, seed=None):
        rng = np.random.RandomState(ndim if seed is None else seed)
        self.a = 10.0 ** rng.uniform(alphamin, alphamax, size=ndim)
        self.b = 10.0 ** rng.uniform(alphamin, alphamax, size=ndim)
        self.ndim = int(ndim)
        self.default_nsteps = 2 * self.ndim + 2

    @property
    def paramnames(self):
        return ['param%d' % (i + 1) for i in range(self.ndim)]

    def __str__(self):
        return 'BetaProduct(ndim=%d)' % self.ndim

    def transform(self, x):
        return np.array(x)

    def to_natural(self, u):
        return np.asarray(u, dtype=float)

    def to_u(self, x):
        return np.asarray(x, dtype=float)

    def loglike(self, theta):
        theta = np.asarray(theta, dtype=float)
        with np.errstate(divide='ignore', invalid='ignore'):
            ll = (self.a - 1) * np.log(theta) \
                + (self.b - 1) * np.log1p(-theta) \
                - special.betaln(self.a, self.b)
        ll = np.where(np.isfinite(ll), ll, -1e300)
        return ll.sum(axis=1)

    def _line_loglike(self, x, v, t):
        """log-likelihood at x + t*v (scalar t).

        The position is clamped into the cube so that rounding at the faces
        gives large finite values (preserving the sign of the limits) rather
        than NaN from log of a slightly negative number.
        """
        xt = np.clip(x + t * v, 1e-16, np.nextafter(1.0, 0.0))
        return np.sum(
            (self.a - 1) * np.log(xt)
            + (self.b - 1) * np.log1p(-xt)
            - special.betaln(self.a, self.b))

    def chord_intervals(self, x, v, Lmin):
        """All t-intervals along x + t*v with loglike >= Lmin, inside the cube."""
        t_lo, t_hi = box_chord_interval(x, v, 0.0, 1.0)

        if np.all(self.a > 1) and np.all(self.b > 1):
            # concave along the line: {loglike >= Lmin} is a single interval
            # containing t=0; loglike -> -inf at both chord endpoints.
            f = lambda t: self._line_loglike(x, v, t) - Lmin
            t_lo_eff = np.nextafter(t_lo, t_hi)
            t_hi_eff = np.nextafter(t_hi, t_lo)
            if t_lo_eff >= t_hi_eff:
                return [(t_lo, t_hi)]
            left = t_lo if f(t_lo_eff) >= 0 else brentq(f, t_lo_eff, 0.0)
            right = t_hi if f(t_hi_eff) >= 0 else brentq(f, 0.0, t_hi_eff)
            return [(left, right)]

        # general case: split the chord at the critical points of the
        # log-likelihood, where it is monotone, and bisect each piece.
        f = lambda t: self._line_loglike(x, v, t) - Lmin
        breakpoints = np.concatenate([
            [t_lo], self._critical_points(x, v, t_lo, t_hi), [t_hi]])
        intervals = []
        for ta, tb in zip(breakpoints[:-1], breakpoints[1:]):
            if not tb > ta:
                continue
            fa = self._line_loglike(x, v, ta) - Lmin
            fb = self._line_loglike(x, v, tb) - Lmin
            if fa >= 0 and fb >= 0:
                intervals.append((ta, tb))
            elif fa >= 0:
                intervals.append((ta, brentq(f, ta, tb)))
            elif fb >= 0:
                intervals.append((brentq(f, ta, tb), tb))
        return self._merge_intervals(intervals)

    @staticmethod
    def _merge_intervals(intervals):
        intervals = sorted((float(lo), float(hi)) for lo, hi in intervals if hi > lo)
        merged = []
        for lo, hi in intervals:
            if merged and lo <= merged[-1][1]:
                merged[-1][1] = max(merged[-1][1], hi)
            else:
                merged.append([lo, hi])
        return [(lo, hi) for lo, hi in merged]

    def _critical_points(self, x, v, t_lo, t_hi):
        """Real roots of d/dt loglike(x + t v) inside (t_lo, t_hi).

        With x_i(t) = x_i + v_i t:

            f'(t) = sum_i v_i [(a_i-1) - (a_i+b_i-2) x_i(t)] / [x_i(t)(1-x_i(t))]

        Multiplying by the positive denominator prod_i x_i(t)(1-x_i(t)) gives
        a polynomial of degree <= 2*ndim-1.
        """
        N = self.ndim
        dfac = [np.array([-v[j] ** 2, v[j] * (1 - 2 * x[j]), x[j] * (1 - x[j])])
                for j in range(N)]
        P = np.zeros(1)
        for i in range(N):
            ni = np.array([
                -v[i] ** 2 * (self.a[i] + self.b[i] - 2),
                v[i] * ((self.a[i] - 1) - (self.a[i] + self.b[i] - 2) * x[i]),
            ])
            prod = ni
            for j in range(N):
                if j != i:
                    prod = np.polymul(prod, dfac[j])
            P = np.polyadd(P, prod)
        P = np.trim_zeros(P, 'f')
        if len(P) < 2:
            return np.array([])
        try:
            roots = np.roots(P)
        except (np.linalg.LinAlgError, ValueError):
            return np.array([])
        roots = np.real(roots[np.abs(roots.imag) < 1e-6])
        return np.sort(roots[(roots > t_lo) & (roots < t_hi)])

    def _axis_extents(self, x, Lmin):
        """Distances from x to the constrained-region boundary along each
        +/- coordinate axis.

        Used only to scale the hit-and-run direction (the proposal stays
        exact for any symmetric direction distribution). The log-likelihood
        along a coordinate axis is piecewise monotone with at most one
        interior extremum, so a coarse scan followed by bisection finds the
        nearest crossing.
        """
        extents = np.empty((self.ndim, 2))
        logB = special.betaln(self.a, self.b)
        for i in range(self.ndim):
            rest = 0.0
            for j in range(self.ndim):
                if j != i:
                    rest += (self.a[j] - 1) * np.log(x[j]) \
                        + (self.b[j] - 1) * np.log1p(-x[j]) - logB[j]
            c_i = Lmin - rest

            def gneg(t):
                t = min(max(t, 1e-16), np.nextafter(1.0, 0.0))
                return (self.a[i] - 1) * np.log(t) \
                    + (self.b[i] - 1) * np.log1p(-t) - logB[i] - c_i

            # scan outward from x[i] along each direction; if no crossing is
            # found, the region extends to the face
            for k, (t_end, t_nocross) in enumerate(((1.0, 1.0), (0.0, 0.0))):
                crossing = t_nocross
                ts = np.linspace(x[i], t_end, 13)[1:]
                prev_t = x[i]
                for t in ts:
                    if gneg(t) < 0:
                        crossing = brentq(gneg, min(prev_t, t), max(prev_t, t))
                        break
                    prev_t = t
                extents[i, k] = abs(crossing - x[i])
        return extents

    def _log_acg(self, u, s):
        """Log density (up to a constant) of the Angular Central Gaussian
        direction distribution with Sigma = diag(s^2) evaluated at u."""
        return -np.log(s).sum() - 0.5 * self.ndim * np.log((u / s ** 2 * u).sum())

    def step(self, x, Lmin, rng):
        """One hit-and-run step over the allowed chord intervals.

        The direction is scaled by the per-axis distances to the region
        boundary, so chords traverse the (possibly spike-shaped,
        strongly anisotropic) constrained region and the chain mixes
        quickly. Because the direction distribution then depends on the
        current position, the move is accepted with a Metropolis-Hastings
        correction (the ratio of Angular Central Gaussian direction
        densities), which restores detailed balance exactly.
        """
        x = np.asarray(x, dtype=float)
        s_x = np.sqrt(self._axis_extents(x, Lmin).prod(axis=1))
        n = rng.normal(size=self.ndim)
        n /= np.linalg.norm(n)
        v = s_x * n
        norm = np.linalg.norm(v)
        if norm <= 0:
            # degenerate: x on the region boundary in all directions
            return x
        u = v / norm
        intervals = self.chord_intervals(x, u, Lmin)
        if len(intervals) == 0:
            return x
        lengths = np.array([hi - lo for lo, hi in intervals])
        i = rng.choice(len(intervals), p=lengths / lengths.sum())
        lo, hi = intervals[i]
        y = x + (lo + (hi - lo) * rng.uniform()) * u

        # Metropolis-Hastings correction: the direction u is distributed as
        # the direction of s(x)*g (g Gaussian), i.e. Angular Central Gaussian
        # with Sigma = diag(s(x)^2)
        s_y = np.sqrt(self._axis_extents(y, Lmin).prod(axis=1))
        log_ratio = self._log_acg(u, s_y) - self._log_acg(u, s_x)
        if np.log(rng.uniform()) > log_ratio:
            return x
        return y

    # ---- analytic reference values ----

    def analytic_lnZ(self):
        # the beta densities integrate to 1 over the unit cube
        return 0.0

    def analytic_H(self):
        ab = self.a + self.b
        e_loglike = (self.a - 1) * (special.psi(self.a) - special.psi(ab)) \
            + (self.b - 1) * (special.psi(self.b) - special.psi(ab)) \
            - special.betaln(self.a, self.b)
        # posterior is the product of betas, lnZ = 0
        return e_loglike.sum()


# ============================================================================
# 4. Gaussian bump with box bonus
# ============================================================================

class BoxGaussianLRPS(Problem):
    """Gaussian bump with a large constant bonus inside a box.

    logL(x) = -0.5 sum_i (x_i/sigma)^2 + logbonus * [max_i x_i < sigma]

    with a flat prior on [0, 1]^N: a Gaussian of width sigma centered on the
    cube corner origin, with a large bonus inside the box [0, sigma]^N.
    The constrained region changes character with the threshold:

    * ``Lmin >= logbonus - 0.5``: a ball (positive-orthant part), sampled directly,
    * ``-0.5 <= Lmin <= logbonus - ndim/2``: exactly the box [0, sigma]^N, sampled directly,
    * ``Lmin <= -ndim/(2 sigma^2)``: the whole cube, sampled directly,
    * otherwise: a union of ball/box pieces, sampled with exact hit-and-run chords.

    The evidence and information gain are analytic.
    """

    def __init__(self, ndim, sigma=0.1, logbonus=100.0):
        self.ndim = int(ndim)
        self.sigma = float(sigma)
        self.logbonus = float(logbonus)
        self.default_nsteps = 2 * self.ndim + 2

    @property
    def paramnames(self):
        return ['param%d' % (i + 1) for i in range(self.ndim)]

    def __str__(self):
        return 'BoxGaussianLRPS(ndim=%d)' % self.ndim

    def transform(self, x):
        return np.array(x)

    def to_natural(self, u):
        return np.asarray(u, dtype=float)

    def to_u(self, x):
        return np.asarray(x, dtype=float)

    def loglike(self, theta):
        theta = np.asarray(theta, dtype=float)
        delta = theta.max(axis=1)
        return -0.5 * ((theta / self.sigma) ** 2).sum(axis=1) \
            + self.logbonus * (delta < self.sigma)

    def step(self, x, Lmin, rng):
        """One exact constrained-prior proposal."""
        # region = {x >= 0, w^2 <= 2 (logbonus - Lmin)}: orthant of a ball
        if Lmin >= self.logbonus - 0.5:
            radius = self.sigma * np.sqrt(2.0 * (self.logbonus - Lmin))
            while True:
                z = sample_uniform_ball(rng, 1, self.ndim, radius)[0]
                if np.all(z >= 0):
                    return z
        # region = the box [0, sigma]^N exactly
        if Lmin >= -0.5 and Lmin <= self.logbonus - 0.5 * self.ndim:
            return rng.uniform(0.0, self.sigma, size=self.ndim)
        # region = the whole cube
        if Lmin <= -0.5 * self.ndim / self.sigma ** 2:
            return rng.uniform(size=self.ndim)
        return self.hit_and_run_step(x, Lmin, rng)

    def hit_and_run_step(self, x, Lmin, rng):
        """Exact hit-and-run step for the mixed box/ball constrained region."""
        x = np.asarray(x, dtype=float)
        v = rng.normal(size=self.ndim)
        v /= np.linalg.norm(v)

        s2 = self.sigma ** 2
        a = np.dot(v, v) / s2
        b = 2.0 * np.dot(x, v) / s2
        c = np.dot(x, x) / s2

        t_lo, t_hi = box_chord_interval(x, v, 0.0, 1.0)
        try:
            b_lo, b_hi = box_chord_interval(x, v, 0.0, self.sigma)
        except ValueError:
            b_lo, b_hi = t_lo, t_lo  # line misses the box

        pieces = []
        # inside the box: w(t)^2 <= 2 (logbonus - Lmin)
        try:
            q1 = quadratic_interval(a, b, c - 2.0 * (self.logbonus - Lmin))
            pieces.append(intersect_intervals((t_lo, t_hi), (b_lo, b_hi), q1))
        except ValueError:
            pass
        # outside the box: w(t)^2 <= -2 Lmin
        if -2.0 * Lmin > 0:
            try:
                q2 = quadratic_interval(a, b, c + 2.0 * Lmin)
                pieces.append(intersect_intervals((t_lo, b_lo), q2))
                pieces.append(intersect_intervals((b_hi, t_hi), q2))
            except ValueError:
                pass

        intervals = self._merge_intervals(pieces)
        if len(intervals) == 0:
            return x
        lengths = np.array([hi - lo for lo, hi in intervals])
        i = rng.choice(len(intervals), p=lengths / lengths.sum())
        lo, hi = intervals[i]
        return x + (lo + (hi - lo) * rng.uniform()) * v

    @staticmethod
    def _merge_intervals(intervals):
        intervals = sorted((float(lo), float(hi)) for lo, hi in intervals if hi > lo)
        merged = []
        for lo, hi in intervals:
            if merged and lo <= merged[-1][1]:
                merged[-1][1] = max(merged[-1][1], hi)
            else:
                merged.append([lo, hi])
        return [(lo, hi) for lo, hi in merged]

    # ---- analytic reference values ----

    def analytic_lnZ(self):
        N = self.ndim
        A = self.sigma * np.sqrt(2 * np.pi)
        q0 = special.ndtr(1.0) - 0.5          # integral over [0, sigma] / A
        q1 = special.ndtr(1.0 / self.sigma) - 0.5  # integral over [0, 1] / A
        # Z = A^N [q0^N e^logbonus + q1^N - q0^N]
        return N * np.log(A) + np.log(
            q0 ** N * np.exp(self.logbonus)
            + q1 ** N - q0 ** N)

    def analytic_H(self):
        N = self.ndim
        A = self.sigma * np.sqrt(2 * np.pi)
        q0 = special.ndtr(1.0) - 0.5
        q1 = special.ndtr(1.0 / self.sigma) - 0.5
        lnZ = self.analytic_lnZ()
        # truncated second moments of the one-sided truncations
        m2_in = 1.0 - _normpdf(1.0) / q0
        hi = 1.0 / self.sigma
        m2_out = 1.0 - hi * _normpdf(hi) / q1
        # integral of L * logL over the box and over cube\box
        I_box = np.exp(self.logbonus) * (A * q0) ** N * (
            self.logbonus - 0.5 * N * m2_in)
        I_out = -0.5 * N * ((A * q1) ** N * m2_out - (A * q0) ** N * m2_in)
        Z = A ** N * (q0 ** N * np.exp(self.logbonus) + q1 ** N - q0 ** N)
        return (I_box + I_out) / Z - lnZ
