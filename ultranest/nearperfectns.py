# 1. Axis-aligned non-isotropic Gaussian likelihood in the unit cube
# ============================================================================

class AsymGauss(Problem):
    """Axis-aligned non-isotropic Gaussian likelihood, flat cube prior.

    logL(x) = -0.5 sum_i ((x_i - mu_i)/sigma_i)^2 - 0.5 sum_i log(2 pi sigma_i^2)

    The posterior is a Gaussian truncated by the cube, so lnZ and H are
    analytic. The widths span 10^max(-1 - 53/ndim, -7) to 0.1, an
    extreme dynamic-range problem.

    The constrained region is an axis-aligned ellipsoid (whitened: a ball)
    clipped by the cube. When it lies fully inside the cube, points are
    drawn directly from it; otherwise a whitened hit-and-run step is used.
    """

    def __init__(self, ndim, mu=0.5):
        log10_sigmamin = max(-1 - 53.0 / ndim, -7)
        self.sigma = np.logspace(log10_sigmamin, -1, ndim)
        self.mu = np.broadcast_to(mu, (ndim,)).astype(float)
        self.ndim = int(ndim)
        self.default_nsteps = 2 * self.ndim + 2

    @property
    def paramnames(self):
        return ['param%d' % (i + 1) for i in range(self.ndim)]

    def __str__(self):
        return 'AsymGauss(ndim=%d)' % self.ndim

    def transform(self, x):
        return np.array(x)

    def to_natural(self, u):
        return (np.asarray(u, dtype=float) - self.mu) / self.sigma

    def to_u(self, z):
        return self.mu + self.sigma * np.asarray(z, dtype=float)

    def loglike(self, theta):
        theta = np.asarray(theta, dtype=float)
        z = (theta - self.mu) / self.sigma
        like = -0.5 * (z ** 2).sum(axis=1) \
            - 0.5 * np.log(2 * np.pi * self.sigma ** 2).sum()
        return np.where(np.isfinite(like), like, -1e300)

    # ---- geometry in whitened coordinates z = (x - mu) / sigma ----

    def _halfwidth(self):
        """Whitened box half-widths, |z_i| <= halfwidth_i inside the cube."""
        return np.minimum(self.mu, 1 - self.mu) / self.sigma

    def _radius(self, Lmin):
        """Whitened radius of the likelihood ellipsoid {logL >= Lmin}."""
        lognorm = 0.5 * np.log(2 * np.pi * self.sigma ** 2).sum()
        return np.sqrt(max(0.0, -2.0 * (Lmin + lognorm)))

    def step(self, z, Lmin, rng):
        """One exact constrained-prior proposal, in whitened coordinates."""
        z = np.asarray(z, dtype=float)
        radius = self._radius(Lmin)
        halfwidth = self._halfwidth()
        if radius <= halfwidth.min():
            # ellipsoid lies inside the cube: sample it directly
            return sample_uniform_ball(rng, 1, self.ndim, radius)[0]
        # whitened hit-and-run step: exact chord through the current point.
        # The direction is scaled to the per-axis extents of the constrained
        # region (an axis-aligned ellipsoid clipped by a box, possibly
        # extremely anisotropic), so that chords traverse the region and the
        # chain mixes quickly. Any symmetric direction distribution gives an
        # exact transition, so this only affects mixing speed.
        n = rng.normal(size=self.ndim)
        n /= np.linalg.norm(n)
        v = np.minimum(halfwidth, radius) * n
        t1 = box_chord_interval(z, v, -halfwidth, halfwidth)
        t2 = quadratic_interval(
            np.dot(v, v), 2.0 * np.dot(z, v), np.dot(z, z) - radius ** 2)
        t_lo, t_hi = intersect_intervals(t1, t2)
        return z + rng.uniform(t_lo, t_hi) * v

    # ---- analytic reference values ----

    def analytic_lnZ(self):
        lo = (0.0 - self.mu) / self.sigma
        hi = (1.0 - self.mu) / self.sigma
        return np.log(special.ndtr(hi) - special.ndtr(lo)).sum()

    def analytic_H(self):
        lo = (0.0 - self.mu) / self.sigma
        hi = (1.0 - self.mu) / self.sigma
        m2 = _truncated_second_moment(lo, hi).sum()
        lognorm = 0.5 * np.log(2 * np.pi * self.sigma ** 2).sum()
        # H = E_posterior[logL] - lnZ
        return -0.5 * m2 - lognorm - self.analytic_lnZ()


