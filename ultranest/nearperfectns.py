"""
Near-perfect samplers for validating nested sampling
====================================================

Toy problems for which the geometry of the prior constrained to
``loglike >= Lmin`` is known analytically. Each problem class provides the
parameter names, transform, (vectorized) log-likelihood, analytic reference
values, and a step sampler that draws from the constrained prior essentially
perfectly:

* where possible, points are sampled *directly* from the constrained region
  (independent draws, no Markov chain),
* otherwise, an exact hit-and-run step is made: the chord through the current
  point is computed analytically and the position along it is drawn from the
  exact 1d conditional prior density (no accept/reject iterations).

Usage::

    from ultranest import ReactiveNestedSampler
    from ultranest.nearperfectns import AsymGauss

    problem = AsymGauss(ndim=2)
    sampler = ReactiveNestedSampler(problem.paramnames, problem.loglike,
                                    transform=problem.transform,
                                    vectorized=True)
    sampler.stepsampler = problem.create_stepsampler()
    result = sampler.run()

    print(result['logz'], problem.analytic_lnZ())

Because the proposals are essentially independent draws from the constrained
prior, the remaining error is the nested sampling statistical error, which
makes these problems useful for checking lnZ, the information gain H, and
the step sampler diagnostics.
"""
import numpy as np
from scipy import special
from scipy.optimize import brentq

from .stepsampler import StepSampler

__all__ = [
    'NearPerfectStepsampler',
    'AsymGauss',
    'Funnel',
    'BetaProduct',
    'BoxGaussianLRPS',
]

_EPS = 1e-14


# ============================================================================
# Geometry utilities
# ============================================================================

def box_chord_interval(x, v, lower, upper):
    """Find the t interval such that lower <= x + t*v <= upper, componentwise.

    Returns (t_lo, t_hi). Raises ValueError if the line does not intersect
    the box.
    """
    x = np.asarray(x, dtype=float)
    v = np.asarray(v, dtype=float)
    lower = np.broadcast_to(lower, x.shape).astype(float)
    upper = np.broadcast_to(upper, x.shape).astype(float)

    t_lo = -np.inf
    t_hi = np.inf

    for xi, vi, lo, hi in zip(x, v, lower, upper):
        if abs(vi) < _EPS:
            if xi < lo or xi > hi:
                raise ValueError("Point is outside box.")
            continue
        a = (lo - xi) / vi
        b = (hi - xi) / vi
        t_lo = max(t_lo, min(a, b))
        t_hi = min(t_hi, max(a, b))

    if t_lo > t_hi:
        raise ValueError("Line does not intersect box.")

    return t_lo, t_hi


def quadratic_interval(a, b, c, tol=_EPS):
    """Solve a*t^2 + b*t + c <= 0 and return the allowed (t_lo, t_hi).

    Handles a ~= 0 (linear constraint). Raises ValueError if there is no
    allowed interval.
    """
    if abs(a) < tol:
        if abs(b) < tol:
            if c <= tol:
                return -np.inf, np.inf
            raise ValueError("No allowed quadratic interval.")
        root = -c / b
        return (-np.inf, root) if b > 0 else (root, np.inf)

    disc = b * b - 4.0 * a * c
    if disc < -tol:
        raise ValueError("No real roots.")
    disc = max(disc, 0.0)
    root_disc = np.sqrt(disc)
    t1 = (-b - root_disc) / (2.0 * a)
    t2 = (-b + root_disc) / (2.0 * a)
    return min(t1, t2), max(t1, t2)


def intersect_intervals(*intervals):
    """Intersect a sequence of (lo, hi) intervals. Raises ValueError if empty."""
    lo = max(interval[0] for interval in intervals)
    hi = min(interval[1] for interval in intervals)
    if lo > hi:
        raise ValueError("Empty intersection.")
    return lo, hi


def sample_uniform_ball(rng, nsamples, ndim, radius):
    """Batched uniform draws from the N-ball ||z|| <= radius."""
    direction = rng.normal(size=(nsamples, ndim))
    direction /= np.linalg.norm(direction, axis=1, keepdims=True)
    radial = radius * rng.uniform(size=nsamples) ** (1.0 / ndim)
    return direction * np.asarray(radial).reshape((-1, 1))


def _normpdf(z):
    return np.exp(-0.5 * np.asarray(z) ** 2) / np.sqrt(2 * np.pi)


def _truncated_second_moment(lo, hi):
    """E[z^2 | lo <= z <= hi] for a standard normal z."""
    p = special.ndtr(hi) - special.ndtr(lo)
    return 1.0 + (lo * _normpdf(lo) - hi * _normpdf(hi)) / p


# ============================================================================
# Near-perfect step sampler
# ============================================================================

class NearPerfectStepsampler(StepSampler):
    """Step sampler that follows the exactly known constrained-prior geometry.

    Each proposal is generated by ``problem.step``: either a direct
    (independent) sample from the prior constrained to ``loglike >= Lmin``,
    or one exact hit-and-run step. Proposals satisfy the likelihood threshold
    by construction, so each proposal costs a single likelihood call and no
    accept/reject tuning is needed.

    Parameters
    ----------
    problem: object
        one of the problem classes in this module (needs step, to_natural,
        to_u and default_nsteps).
    nsteps: int
        number of proposals until a sample is considered independent. Only
        relevant for the hit-and-run phases; direct phases produce
        independent draws at every step.
    check_nsteps: str or False
        diagnostics recorded per chain, see
        :py:class:`ultranest.stepsampler.StepSampler`.
    """

    def __init__(self, problem, nsteps=None, check_nsteps='move-distance',
                 region_filter=False):
        if nsteps is None:
            nsteps = problem.default_nsteps
        StepSampler.__init__(
            self, nsteps=nsteps, generate_direction=None,
            region_filter=region_filter, check_nsteps=check_nsteps)
        self.problem = problem

    def __str__(self):
        return '%s(%s, nsteps=%d)' % (type(self).__name__, self.problem, self.nsteps)

    def __next__(self, region, Lmin, us, Ls, transform, loglike, ndraw=10,
                 plot=False, tregion=None):
        self._Lmin = Lmin
        return StepSampler.__next__(
            self, region, Lmin, us, Ls, transform, loglike,
            ndraw=ndraw, plot=plot, tregion=tregion)

    def move(self, ui, region, ndraw=1, plot=False):
        x = self.problem.to_natural(np.asarray(ui, dtype=float))
        try:
            xnew = self.problem.step(x, self._Lmin, np.random)
            unew = np.asarray(self.problem.to_u(xnew), dtype=float)
        except (ValueError, np.linalg.LinAlgError, FloatingPointError):
            unew = np.asarray(ui, dtype=float)
        if not (np.all(unew > 0) and np.all(unew < 1)):
            # degenerate geometry (e.g. current point on the region boundary):
            # remain at the current point
            unew = np.asarray(ui, dtype=float)
        return unew.reshape((1, -1))


class Problem:
    """Mixin giving the problem classes a create_stepsampler factory."""

    def create_stepsampler(self, nsteps=None, check_nsteps='move-distance'):
        """Return a :py:class:`NearPerfectStepsampler` for this problem."""
        return NearPerfectStepsampler(self, nsteps=nsteps, check_nsteps=check_nsteps)


