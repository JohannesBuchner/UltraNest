# 2. Funnel: s = log(sigma) ~ Normal(0, tau^2), w_i ~ Uniform[-D, D]
# ============================================================================

class Funnel(Problem):
    """Funnel problem in the coordinates s = log(sigma), w_i.

    Prior: s ~ Normal(0, tau^2), w_i ~ Uniform[-D, D]; the nested sampling
    parameters are (sigma, dp_1..dp_N) with dp = L w, where L is the
    Cholesky matrix of M, the correlation matrix with off-diagonals gamma.
    Likelihood:

        logL = -0.5 dp' M^-1 dp - N log(sigma)
               - 0.5 (N log(2 pi) + log det M)

    In (s, w) coordinates the likelihood contour is the paraboloid

        |w|^2 + 2 N s <= C,   |w_i| <= D.

    Chords are analytic and, because of the Gaussian prior in s, the exact
    position along a chord is a truncated normal. The likelihood grows
    towards small sigma, so the thin funnel neck at small sigma must be
    resolved exactly. The untruncated funnel is only a faithful lnZ test
    problem while N * tau is small (the posterior mode of s at -N tau^2
    must stay within reach of the live-point population); use large
    nlive points, or truncate the s-prior, at higher dimensions.
    """

    def __init__(self, ndim, tau=0.5, D=10.0, gamma=0.0):
        assert ndim > 0
        self.ndim = int(ndim)  # number of dp parameters; total dim = ndim + 1
        self.tau = float(tau)
        self.D = float(D)
        M = np.full((ndim, ndim), gamma, dtype=float)
        np.fill_diagonal(M, 1.0)
        self.M = M
        self.Minv = np.linalg.inv(M)
        self.L = np.linalg.cholesky(M)
        self.logdetM = float(np.linalg.slogdet(M)[1])
        self.default_nsteps = 4 * (self.ndim + 1)

    @property
    def s_lower(self):
        return -np.inf

    @property
    def s_upper(self):
        return np.inf

    @property
    def paramnames(self):
        return ['sigma'] + ['dp%d' % i for i in range(self.ndim)]

    def __str__(self):
        return 'Funnel(ndim=%d, tau=%g, D=%g, gamma=%g)' % (
            self.ndim, self.tau, self.D, self.M[0, 1])

    def transform(self, u):
        u = np.asarray(u, dtype=float)
        with np.errstate(divide='ignore', invalid='ignore'):
            s = self.tau * special.ndtri(u[:, 0])
            w = u[:, 1:] * 2 * self.D - self.D
            d = w @ self.L.T
            return np.concatenate([np.exp(s)[:, None], d], axis=1)

    def to_natural(self, u):
        u = np.asarray(u, dtype=float)
        return self.tau * special.ndtri(u[0]), 2 * self.D * u[1:] - self.D

    def to_u(self, state):
        s, w = state
        u0 = special.ndtr(np.asarray(s, dtype=float) / self.tau)
        ui = (np.asarray(w, dtype=float) + self.D) / (2 * self.D)
        return np.concatenate([np.atleast_1d(u0), np.atleast_1d(ui)])

    def loglike(self, theta):
        theta = np.asarray(theta, dtype=float)
        with np.errstate(divide='ignore', invalid='ignore'):
            s = np.log(theta[:, 0])
            d = theta[:, 1:]
            r = np.einsum('ij,jk,ik->i', d, self.Minv, d)
            like = -0.5 * (r + 2 * self.ndim * s
                           + self.ndim * np.log(2 * np.pi) + self.logdetM)
        return np.where(np.isfinite(like), like, -1e300)

    def step(self, state, Lmin, rng):
        """One exact hit-and-run step in the (s, w) coordinates."""
        s = float(state[0])
        w = np.asarray(state[1], dtype=float)
        C = -2.0 * (Lmin + 0.5 * (self.ndim * np.log(2 * np.pi) + self.logdetM))

        # direction in prior-scaled coordinates
        g = rng.normal(size=self.ndim + 1)
        g /= np.linalg.norm(g)
        vs = self.tau * g[0]
        vw = self.D * g[1:]

        # chord: |w + t vw| <= D  and  |w + t vw|^2 + 2 N (s + t vs) <= C
        t1 = box_chord_interval(w, vw, -self.D, self.D)
        t2 = quadratic_interval(
            np.dot(vw, vw),
            2.0 * np.dot(w, vw) + 2.0 * self.ndim * vs,
            np.dot(w, w) + 2.0 * self.ndim * s - C,
        )
        t_lo, t_hi = intersect_intervals(t1, t2)

        # exact conditional along the chord: p(s(t)) ~ exp(-s(t)^2/(2 tau^2)),
        # i.e. t is a truncated normal
        if abs(vs) > _EPS:
            mean = -s / vs
            scale = self.tau / abs(vs)
            a = (t_lo - mean) / scale
            b = (t_hi - mean) / scale
            u = rng.uniform(special.ndtr(a), special.ndtr(b))
            if 0.0 < u < 1.0:
                t = mean + scale * special.ndtri(u)
            else:
                # CDF underflow far in the tail: fall back to uniform on chord
                t = rng.uniform(t_lo, t_hi)
        else:
            t = rng.uniform(t_lo, t_hi)
        return s + t * vs, w + t * vw

    # ---- analytic reference values ----

    def analytic_lnZ(self):
        nd = self.ndim
        q = 2 * special.ndtr(self.D) - 1  # P(|z| <= D)
        # Z = [(2 Phi(D) - 1) / (2 D)]^N * exp(N^2 tau^2 / 2) * det(M)^-1/2
        return nd * np.log(q / (2 * self.D)) + 0.5 * nd ** 2 * self.tau ** 2 \
            - 0.5 * self.logdetM

    def analytic_H(self):
        nd = self.ndim
        q = 2 * special.ndtr(self.D) - 1
        m2 = 1.0 - 2 * self.D * _normpdf(self.D) / q  # E[z^2 | |z| <= D]
        lognorm = 0.5 * (nd * np.log(2 * np.pi) + self.logdetM)
        # posterior factorises: s ~ Normal(-N tau^2, tau^2), d_i ~ Normal(0,1) truncated
        e_logl = -0.5 * nd * m2 + nd ** 2 * self.tau ** 2 - lognorm
        return e_logl - self.analytic_lnZ()


